"""Reduce native evidence to exact private bindings and address-byte corrections."""
import json,struct,gzip,sys,hashlib
from pathlib import Path
from map_private_rvas import Image,OLD,NEW,find_masked,neutral,DECODER
root=Path(r'D:\_Ugit\FSTool\_Mod\Topics\Gameplay\bug-er-1-17-2-dll-compat')
proof_path=root/'scale-reachable-binding-proof.json'
proof_bytes=proof_path.read_bytes() if proof_path.exists() else gzip.decompress(proof_path.with_suffix('.json.gz').read_bytes())
proof=json.loads(proof_bytes)
if '--check-input' in sys.argv:
    assert not proof['conflicts'] and proof['instruction_count']==160070
    print('PASS proof readback:',hashlib.sha256(proof_bytes).hexdigest(),proof['instruction_count'])
    sys.exit(0)
assert not proof['conflicts']
bindings={int(a,16):int(b,16) for a,b in proof['bindings'].items()}
types=json.loads((root/'scale-type-mapping.json').read_text())
code=json.loads((root/'scale-code-mapping.json').read_text())['results']
old,new=Image(OLD),Image(NEW)
extra=[]
for item in types:
    a=int(item['old'],16)
    if item.get('new') or a in bindings:continue
    raw=old.data(a,64)
    expected=bytearray(64);mask=bytearray(64);known=[]
    for slot in range(8):
        word=struct.unpack('<Q',raw[slot*8:slot*8+8])[0]
        rva=word-old.base
        if rva in bindings:
            value=new.base+bindings[rva]
            known.append(slot)
        elif old.base<=word<old.base+old.pe.OPTIONAL_HEADER.SizeOfImage:continue
        else:value=word
        expected[slot*8:slot*8+8]=struct.pack('<Q',value)
        mask[slot*8:slot*8+8]=b'\xff'*8
    assert sum(mask)>=16*255,(hex(a),known)
    hits=[]
    for h in find_masked(new.pe.__data__,bytes(expected),bytes(mask)):
        try:b=new.pe.get_rva_from_offset(h)
        except Exception:continue
        if 0x29b4000<=b<0x3b18000:hits.append(b)
    assert len(hits)==1,(hex(a),[hex(v) for v in hits])
    bindings[a]=hits[0]
    functions=[]
    for slot in range(8):
        x=struct.unpack('<Q',raw[slot*8:slot*8+8])[0]-old.base
        y=struct.unpack('<Q',new.data(hits[0]+slot*8,8))[0]-new.base
        if old.lo<=x<old.lo+len(old.code):
            xx,yy=x,y
            for _ in range(8):
                before=next(DECODER.disasm(old.data(xx,16),xx,1))
                after=next(DECODER.disasm(new.data(yy,16),yy,1))
                assert neutral(before.bytes,xx)[0]==neutral(after.bytes,yy)[0],(hex(xx),hex(yy))
                if before.mnemonic in ('ret','jmp','int3'):break
                xx+=before.size;yy+=after.size
            functions.append([hex(x),hex(y)])
    extra.append({'old':hex(a),'new':hex(hits[0]),'method':'unique mixed pointer-table and adjacent literal context','known_slots':known,'function_prefixes':functions})

wanted={int(v['old'],16) for v in types}
wanted.update(int(v['old'],16) for v in code if int(v['old'],16)>0x3b0000)
missing=[a for a in wanted if a not in bindings and a not in (0x7dd67e,0x24fe160)]
assert not missing,[hex(a) for a in missing]
pairs=sorted((a,bindings[a]) for a in wanted if a in bindings)
inverse=sorted((b,a) for a,b in pairs)
assert len({b for b,a in inverse})==len(inverse),'ambiguous inverse private RVA'
code_sites=sorted(a for a,b in pairs if a<0x29b2000)
fixups=[(int(a,16),v,w) for a,v,w in proof['byte_fixups'] if any(site<=int(a,16)<site+256 for site in code_sites)]
lines=['// Generated by generate_scale_profile.py from fixed EXE/RTTI/CFG evidence.',
       'pub(super) const BINDINGS: &[(usize,usize)] = &[']
lines += [f'    (0x{a:x},0x{b:x}),' for a,b in pairs]
lines += ['];','pub(super) const INVERSE: &[(usize,usize)] = &[']
lines += [f'    (0x{a:x},0x{b:x}),' for a,b in inverse]
lines += ['];','pub(super) const ADDRESS_BYTES: &[(usize,u8,u8)] = &[']
lines += [f'    (0x{a:x},0x{v:x},0x{w:x}),' for a,v,w in fixups]
lines += ['];']
Path(r'D:\_Ugit\FSTool\_Mod\_Project\ERCharacterScale\src\compatibility_data.rs').write_text('\n'.join(lines)+'\n')
(root/'scale-private-profile.json').write_text(json.dumps({'pairs':[[hex(a),hex(b)] for a,b in pairs],
    'address_byte_corrections':len(fixups),'extra_pointer_tables':extra,'skipped':['NR diagnostic string 0x7dd67e','PE entry uses profile identity, not callable RVA'],
    'reachable_instructions':proof['instruction_count'],'discarded_prefix_candidates':proof['discarded_prefix_candidates']},indent=2))
print('private pairs',len(pairs),'address-byte corrections',len(fixups),'extra tables',extra)
